function compile(art: string): Uint8Array {
  const rows = art.split(' ')
  const mask = new Uint8Array(GLYPH_H)
  for (let y = 0; y < GLYPH_H; y++) {
    let bits = 0
    for (let x = 0; x < GLYPH_W; x++) {
      if (rows[y][x] === '#') bits |= 1 << (GLYPH_W - 1 - x)
    }
    mask[y] = bits
  }
  return mask
}

const COMPILED = new Map<string, Uint8Array>(
  Object.entries(GLYPHS).map(([char, art]) => [char, compile(art)]),
)

const BLANK = COMPILED.get(' ') as Uint8Array

/** The bitmask rows for a character; unsupported characters render blank. */
export function glyphFor(char: string): Uint8Array {
  return COMPILED.get(char.toUpperCase()) ?? BLANK
}

/** Width in virtual pixels of `text` at a given scale and letter spacing. */
export function measureText(
  text: string,
  scale: number,
  tracking: number,
): number {
  if (text.length === 0) return 0
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale
}
